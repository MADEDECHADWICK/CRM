# Starts / prepares the CRM demo on this machine.
#   .\demo.ps1          -> starts the DB, detects your LAN IP, writes apps/mobile/.env, prints how to run
#   .\demo.ps1 -Run     -> also opens the API, web and mobile in separate windows
param([switch]$Run)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

Write-Host "== 1. Database ==" -ForegroundColor Cyan
docker start crm-audit-pg | Out-Null
Start-Sleep -Seconds 4
docker ps --filter name=crm-audit-pg --format "DB: {{.Names}} {{.Status}}"

Write-Host "`n== 2. Detect LAN IP ==" -ForegroundColor Cyan
$ip = (Get-NetIPConfiguration | Where-Object { $_.IPv4DefaultGateway } | Select-Object -First 1).IPv4Address.IPAddress
if (-not $ip) {
  Write-Host "No adapter with a default gateway found. Connect to Wi-Fi and retry." -ForegroundColor Red
  exit 1
}
Write-Host "LAN IP: $ip" -ForegroundColor Green

Write-Host "`n== 3. Pin the mobile API URL ==" -ForegroundColor Cyan
Set-Content -Path (Join-Path $root "apps\mobile\.env") -Value "# auto-generated by demo.ps1`nEXPO_PUBLIC_API_URL=http://${ip}:4000"
Write-Host "apps/mobile/.env -> http://${ip}:4000"

Write-Host "`n== 4. Ensure the web bundle is built ==" -ForegroundColor Cyan
if (-not (Test-Path (Join-Path $root "apps\web\dist\index.html"))) {
  Write-Host "Building web bundle..."
  pnpm --filter web build
} else {
  Write-Host "apps/web/dist already present."
}

Write-Host "`n== PHONE CHECK ==" -ForegroundColor Yellow
Write-Host "On the phone's browser open:  http://${ip}:4000/   -> expect {`"success`":true,...}"
Write-Host "If that fails, open the firewall once (PowerShell as Administrator):"
Write-Host "  New-NetFirewallRule -DisplayName 'CRM API 4000'  -Direction Inbound -Protocol TCP -LocalPort 4000 -Action Allow -Profile Any"
Write-Host "  New-NetFirewallRule -DisplayName 'CRM Expo 8081' -Direction Inbound -Protocol TCP -LocalPort 8081 -Action Allow -Profile Any"

if (-not $Run) {
  Write-Host "`n== START (3 terminals, from $root) ==" -ForegroundColor Green
  Write-Host "  API : `$env:DATABASE_URL='postgresql://crm_audit:audit-local-pw@127.0.0.1:5433/crm_audit'; `$env:API_PORT='4000'; pnpm --filter api dev"
  Write-Host "  WEB : pnpm --filter web serve     (then open http://localhost:8080)"
  Write-Host "  MOB : pnpm --filter mobile start --clear"
  exit 0
}

Write-Host "`nLaunching API, web and mobile in separate windows..." -ForegroundColor Green
Start-Process powershell -ArgumentList '-NoExit','-Command',"cd '$root'; `$env:DATABASE_URL='postgresql://crm_audit:audit-local-pw@127.0.0.1:5433/crm_audit'; `$env:API_PORT='4000'; pnpm --filter api dev"
Start-Process powershell -ArgumentList '-NoExit','-Command',"cd '$root'; pnpm --filter web serve"
Start-Process powershell -ArgumentList '-NoExit','-Command',"cd '$root'; pnpm --filter mobile start --clear"
